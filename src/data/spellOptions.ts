/**
 * Get spells available to a specific class at character creation
 * Uses proper class-to-spell mappings instead of hardcoded filtering
 */
export const getClassSpells = (className: string): { cantrips: Spell[], spells: Spell[] } => {
  const mapping = classSpellMappings[className as keyof typeof classSpellMappings];

  if (!mapping) {
    return { cantrips: [], spells: [] };
  }

  return {
    cantrips: cantrips.filter(spell => mapping.cantrips.includes(spell.id)),
    spells: firstLevelSpells.filter(spell => mapping.spells.includes(spell.id))
  };
};

/**
 * Get all spells by school for filtering
 */
export const getSpellsBySchool = (school: string): Spell[] => {
  return allSpells.filter(spell => spell.school === school);
};

/**
 * Get spells by level
 */
export const getSpellsByLevel = (level: number): Spell[] => {
  return allSpells.filter(spell => spell.level === level);
};

/**
 * Get ritual spells
 */
export const getRitualSpells = (): Spell[] => {
  return allSpells.filter(spell => spell.ritual);
};

/**
 * Get concentration spells
 */
export const getConcentrationSpells = (): Spell[] => {
  return allSpells.filter(spell => spell.concentration);
};

/**
 * Search spells by name
 */
export const searchSpells = (query: string): Spell[] => {
  const lowercaseQuery = query.toLowerCase();
  return allSpells.filter(spell =>
    spell.name.toLowerCase().includes(lowercaseQuery) ||
    spell.description.toLowerCase().includes(lowercaseQuery)
  );
};

/**
 * Get spell by ID
 */
export const getSpellById = (id: string): Spell | undefined => {
  return allSpells.find(spell => spell.id === id);
};

/**
 * Validate spell selection for a character class
 */
export const validateSpellSelection = (
  className: string,
  selectedCantrips: string[],
  selectedSpells: string[]
): { valid: boolean; errors: string[] } => {
  const classSpells = getClassSpells(className);
  const errors: string[] = [];

  // Check cantrips
  selectedCantrips.forEach(cantripId => {
    if (!classSpells.cantrips.some(cantrip => cantrip.id === cantripId)) {
      errors.push(`${cantripId} is not available as a cantrip for ${className}`);
    }
  });

  // Check spells
  selectedSpells.forEach(spellId => {
    if (!classSpells.spells.some(spell => spell.id === spellId)) {
      errors.push(`${spellId} is not available as a 1st level spell for ${className}`);
    }
  });

  return {
    valid: errors.length === 0,
    errors
  };
};

